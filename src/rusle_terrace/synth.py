"""Deterministic synthetic DEM for the ``rusle demo`` command.

The surface is a south-facing slope with three terrace benches. It is an
analytic construction, not an observed DEM; the analytic parameters are stored
next to the raster in ``dem_truth.json``.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import rasterio

SHAPE = (300, 300)
CELLSIZE = 30.0
CRS = "EPSG:32647"
ORIGIN = (500_000.0, 2_800_000.0)
BASE_ELEVATION = 1150.0
TERRACE_PERIOD_M = 3000.0
TREAD_M = 2300.0
TREAD_SLOPE = 0.03
RISER_SLOPE = 0.32
# Two cross-slope waves (amplitude m, wavelength m) so flow splits and does not
# converge into one corner.
CROSS_WAVES = ((9.0, 2600.0), (3.0, 950.0))
NODATA_PATCH = (slice(2, 20), slice(4, 28))

DEMO_PARAMS = """\
# Synthetic demonstration parameters (not calibrated to a real vineyard).
annual_precip_mm: 620
sand_pct: 45
silt_pct: 35
clay_pct: 20
organic_carbon_pct: 1.2
cover_factor: 0.25
support_practice: terraces
slope_classes_deg: [0, 5, 10, 15, 25, 90]
"""


def _surface(rows: int, cols: int, cellsize: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return elevation, dz/dy (south-positive) and dz/dx arrays."""
    y = np.arange(rows)[:, None] * cellsize
    x = np.arange(cols)[None, :] * cellsize
    phase = np.mod(y, TERRACE_PERIOD_M)
    cycles = np.floor_divide(y, TERRACE_PERIOD_M)
    drop = (
        cycles * (TREAD_SLOPE * TREAD_M + RISER_SLOPE * (TERRACE_PERIOD_M - TREAD_M))
        + np.minimum(phase, TREAD_M) * TREAD_SLOPE
        + np.maximum(phase - TREAD_M, 0.0) * RISER_SLOPE
    )
    cross = np.zeros_like(x, dtype="float64")
    dz_dx = np.zeros_like(x, dtype="float64")
    for amplitude, wavelength in CROSS_WAVES:
        cross = cross + amplitude * np.sin(2.0 * np.pi * x / wavelength)
        dz_dx = dz_dx + amplitude * 2.0 * np.pi / wavelength * np.cos(
            2.0 * np.pi * x / wavelength
        )
    z = BASE_ELEVATION - drop + cross
    dz_dy = np.where(phase < TREAD_M, TREAD_SLOPE, RISER_SLOPE)
    dz_dy = np.broadcast_to(dz_dy, z.shape).astype("float64")
    dz_dx = np.broadcast_to(dz_dx, z.shape).astype("float64")
    return z, dz_dy, dz_dx


def generate_demo(outdir: str | Path) -> dict[str, Path]:
    """Write ``dem.tif``, ``params.yaml`` and ``dem_truth.json`` into ``outdir``."""
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    rows, cols = SHAPE
    z, dz_dy, dz_dx = _surface(rows, cols, CELLSIZE)
    valid = np.ones(z.shape, dtype=bool)
    valid[NODATA_PATCH] = False
    z_out = np.where(valid, z, -9999.0)

    transform = rasterio.Affine(CELLSIZE, 0.0, ORIGIN[0], 0.0, -CELLSIZE, ORIGIN[1])
    dem_path = out / "dem.tif"
    with rasterio.open(
        dem_path,
        "w",
        driver="GTiff",
        height=rows,
        width=cols,
        count=1,
        dtype="float32",
        crs=CRS,
        transform=transform,
        nodata=-9999.0,
        compress="deflate",
    ) as dst:
        dst.write(z_out.astype("float32"), 1)
        dst.set_band_description(1, "synthetic terraced south slope, 30 m")

    slope_deg = np.degrees(np.arctan(np.hypot(dz_dx, dz_dy)))
    tread = (np.mod(np.arange(rows)[:, None] * CELLSIZE, TERRACE_PERIOD_M) < TREAD_M)
    truth = {
        "synthetic": True,
        "note": "Analytic surface, not an observed DEM. Three terrace benches."
        " Generated by `rusle demo`.",
        "crs": CRS,
        "cell_size_m": CELLSIZE,
        "shape": [rows, cols],
        "nodata_cells": int((~valid).sum()),
        "elevation_m": {"min": float(z[valid].min()), "max": float(z[valid].max())},
        "analytic_slope_deg": {
            "min": round(float(slope_deg[valid].min()), 3),
            "median": round(float(np.median(slope_deg[valid])), 3),
            "max": round(float(slope_deg[valid].max()), 3),
            "tread_mean": round(float(slope_deg[valid & tread].mean()), 3),
            "riser_mean": round(float(slope_deg[valid & ~tread].mean()), 3),
        },
        "design": {
            "aspect": "south-facing",
            "terraces": 3,
            "terrace_period_m": TERRACE_PERIOD_M,
            "tread_m": TREAD_M,
            "tread_slope": TREAD_SLOPE,
            "riser_slope": RISER_SLOPE,
            "cross_waves_amplitude_m_wavelength_m": [list(w) for w in CROSS_WAVES],
        },
    }
    truth_path = out / "dem_truth.json"
    truth_path.write_text(json.dumps(truth, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    params_path = out / "params.yaml"
    params_path.write_text(DEMO_PARAMS, encoding="utf-8")
    return {"dem": dem_path, "params": params_path, "truth": truth_path}


def is_synthetic_dem(dem_path: str | Path) -> bool:
    """True when a sibling ``dem_truth.json`` marks the DEM as synthetic."""
    truth = Path(dem_path).with_name("dem_truth.json")
    if not truth.is_file():
        return False
    try:
        return bool(json.loads(truth.read_text(encoding="utf-8")).get("synthetic"))
    except (OSError, json.JSONDecodeError):
        return False
